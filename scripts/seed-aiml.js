async function seed() {
  let inserted = 0, skipped = 0, failed = 0;
  for (const s of aiml) {
    try {
      await axios.post(SERVER+'/api/students', s, {headers:{'Content-Type':'application/json'}});
      console.log(`✅ ${s.enrollmentNo} - ${s.name}`);
      inserted++;
    } catch(e) {
      const msg = e.response?.data?.error || e.message || '';
      if (msg.includes('E11000') || msg.includes('duplicate')) {
        console.log(`⏭️  SKIP ${s.enrollmentNo} (already exists)`);
        skipped++;
      } else {
        console.error(`❌ FAIL ${s.enrollmentNo}: ${msg}`);
        failed++;
      }
    }
  }
  console.log(`\n📊 AIML done — inserted: ${inserted}, skipped: ${skipped}, failed: ${failed}`);
}
